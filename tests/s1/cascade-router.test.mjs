// AC31, AC33 and AC41: the plain GitHub Actions event router .github/workflows/cascade-router.yml.
import assert from "node:assert/strict";
import test from "node:test";
import YAML from "yaml";
import { renderFleet } from "../../src/reconcile.mjs";
import { abs, clone, edgeOf, fixture, minimalManifest, mutate, presetManifest, readText, referenceRequest, toYaml } from "./helpers/fixtures.mjs";
import { createWorkspace } from "./helpers/workspace.mjs";

const ROUTER = ".github/workflows/cascade-router.yml";
const request = referenceRequest();
const preset = presetManifest();
const committed = YAML.parse(readText(abs(ROUTER)));
const renderedText = renderFleet(request).files.get(ROUTER);
const rendered = YAML.parse(renderedText);

const jobOf = (workflow) => {
  const names = Object.keys(workflow.jobs);
  assert.equal(names.length, 1, "the router has one matrix job");
  return workflow.jobs[names[0]];
};

/** Renders a manifest in a throwaway workspace and returns the parsed router. */
function routerFor(manifest, extraFiles = {}) {
  const workspace = createWorkspace({ manifestText: toYaml(manifest), instructions: true, files: extraFiles });
  try {
    const result = renderFleet(request, { cwd: workspace.dir });
    assert.ok(result.ok, JSON.stringify(result.result));
    return YAML.parse(result.files.get(ROUTER));
  } finally {
    workspace.cleanup();
  }
}

test("AC31: the committed router equals the fresh render byte for byte and is a plain Actions workflow", () => {
  assert.equal(readText(abs(ROUTER)).replace(/\r\n/g, "\n"), renderedText);
  assert.equal(renderedText.startsWith("# Generated by "), true, "a generated-file header comment leads the file");
  for (const router of [committed, rendered]) {
    assert.equal(typeof router.name, "string");
    assert.ok(router.jobs && router.on);
    assert.equal("safe-outputs" in router, false, "not a gh-aw source");
    assert.equal("engine" in router, false);
  }
  assert.equal(renderedText.includes("\r"), false);
});

test("AC31: on carries exactly repository_dispatch, schedule and workflow_dispatch", () => {
  for (const router of [committed, rendered]) {
    assert.deepEqual(Object.keys(router.on).sort(), ["repository_dispatch", "schedule", "workflow_dispatch"]);
    assert.deepEqual(router.on.repository_dispatch.types, ["upstream_pr_merged"]);
    assert.equal(router.on.workflow_dispatch.inputs.reset_blocked.type, "boolean");
    assert.deepEqual(Object.keys(router.on.workflow_dispatch.inputs), ["reset_blocked"]);
  }
});

test("AC31: on.schedule holds one cron per distinct non-null edge schedule, sorted", () => {
  assert.deepEqual(rendered.on.schedule, [{ cron: "0 */6 * * *" }]);
  const varied = mutate(preset, (copy) => {
    copy.dependencyEdges[0].schedule = "30 8 * * *";
    copy.dependencyEdges[1].schedule = "0 */2 * * *";
    copy.dependencyEdges[2].schedule = null;
    copy.dependencyEdges[3].schedule = "30 8 * * *";
    copy.dependencyEdges[4].schedule = "30 8 * * *";
  });
  assert.deepEqual(routerFor(varied).on.schedule, [{ cron: "0 */2 * * *" }, { cron: "30 8 * * *" }]);
  const unscheduled = mutate(preset, (copy) => copy.dependencyEdges.forEach((edge) => (edge.schedule = null)));
  const router = routerFor(unscheduled);
  assert.equal(router.on.schedule === undefined || router.on.schedule.length === 0, true, "no cron entry when no edge is scheduled");
});

