test("AC31: the matrix job checks out the orchestrator, installs with --ignore-scripts, then runs the routing step", () => {
  const steps = jobOf(rendered).steps;
  const routing = steps.findIndex((step) => typeof step.run === "string" && step.run.includes("src/route-upstream.mjs"));
  assert.ok(routing >= 2, "the routing step exists after two earlier steps");
  assert.equal(steps[0].uses, "actions/checkout@v4");
  assert.deepEqual(steps[0].with, { "persist-credentials": false });
  assert.deepEqual(steps[1], { run: "npm ci --ignore-scripts" });
  assert.equal(steps[routing].run, 'node "$GITHUB_WORKSPACE/src/route-upstream.mjs"');
  assert.equal(steps.filter((step) => String(step.run ?? "").includes("route-upstream.mjs")).length, 1, "one routing step");
  assert.equal(steps.length, 3);
});

test("AC31: the matrix gains an entry when an edge is added to a fixture manifest", () => {
  const base = mutate(minimalManifest(), () => {});
  const before = jobOf(routerFor(base)).strategy.matrix;
  assert.deepEqual(before.upstreamKey, ["alpha-service"]);
  const grown = mutate(base, (copy) => {
    const second = clone(copy.dependencyEdges[0]);
    Object.assign(second, {
      edgeId: "gamma-to-beta",
      upstreamRepo: "initech/gamma",
      upstreamKey: "gamma",
      upstreamSlug: "GAMMA",
      stateVariable: "SDLC_SYNC_STATE_GAMMA",
      branchName: "sdlc/cascade-gamma-to-beta",
      closeOlderKey: "sdlc-cascade-gamma-to-beta",
    });
    copy.dependencyEdges.push(second);
  });
  const after = jobOf(routerFor(grown)).strategy.matrix;
  assert.deepEqual(after.upstreamKey, ["alpha-service", "gamma"]);
  assert.equal(after.include.length, before.include.length + 1);
  assert.deepEqual(after.include.map((entry) => entry.edgeId), ["alpha-to-beta", "gamma-to-beta"]);
});

const EDGE_KEYS = {
  upstreamRepo: "string", upstreamKey: "string", upstreamSlug: "string", upstreamDefaultBranch: "string", initialBaselineSha: "string",
  downstreamRepo: "string", mode: "string", schedule: "nullable-string", onCommitOnlyAdvance: "string", stateVariable: "string",
  provenanceFile: "string", provenanceJsonPointer: "string", onBots: "string[]", branchName: "string", closeOlderKey: "string",
  reviewers: "string[]", importCommands: "string[]", buildCommands: "string[]", verifyCommands: "string[]", edgeId: "string",
  preflightCommands: "string[]",
};

function assertTyped(value, type, label) {
  if (type === "string") assert.equal(typeof value, "string", label);
  else if (type === "nullable-string") assert.ok(value === null || typeof value === "string", label);
  else assert.ok(Array.isArray(value) && value.every((item) => typeof item === "string"), label);
}

test("AC33: every matrix entry carries the 19 keys of contract C3 plus edgeId and preflightCommands, typed as shown", () => {
  for (const router of [committed, rendered]) {
    const { include } = jobOf(router).strategy.matrix;
    assert.equal(include.length, preset.dependencyEdges.length);
    include.forEach((entry, index) => {
      assert.deepEqual(Object.keys(entry).sort(), Object.keys(EDGE_KEYS).sort(), `entry ${index}`);
      for (const [key, type] of Object.entries(EDGE_KEYS)) assertTyped(entry[key], type, `${entry.edgeId}.${key}`);
      assert.match(entry.initialBaselineSha, /^[0-9a-f]{40}$/);
      assert.ok(["mechanical", "ai-adaptation"].includes(entry.mode));
      assert.ok(["noop", "bump-provenance"].includes(entry.onCommitOnlyAdvance));
      assert.deepEqual(entry.onBots, ["mfg-msft-ai-sdlc[bot]"], "onBots is derived from appSlug and never authored");
    });
    assert.equal(Object.keys(EDGE_KEYS).length, 21);
  }
});

test("AC33: each matrix entry carries its resolved edge, in manifest order", () => {
  const { include } = jobOf(rendered).strategy.matrix;
  preset.dependencyEdges.forEach((edge, index) => {
    const entry = include[index];
    for (const key of Object.keys(EDGE_KEYS).filter((name) => name !== "onBots")) assert.deepEqual(entry[key], edge[key], `${edge.edgeId}.${key}`);
  });
});

test("AC33: the matrix entry does not carry the policy keys that only the workflow needs", () => {
  const { include } = jobOf(rendered).strategy.matrix;
  for (const entry of include) {
    for (const key of ["acceptCommands", "allowedFiles", "adaptationInstructions", "immutableGates", "protectedFilesExclude", "autoMerge", "syncScopes", "installDirectories"]) {
      assert.equal(key in entry, false, `${entry.edgeId} must not carry ${key}`);
    }
  }
});

test("AC41: the router masks no failure: no continue-on-error, no forced-success fallback", () => {
  for (const text of [renderedText, readText(abs(ROUTER))]) {
    assert.equal(/continue-on-error:\s*true/.test(text), false);
    assert.equal(/\|\|\s*(true|:)\s*$/m.test(text), false);
    assert.equal(/;\s*exit\s+0\s*$/m.test(text), false);
  }
  const walk = (value, visit) => {
    if (Array.isArray(value)) value.forEach((item) => walk(item, visit));
    else if (value && typeof value === "object") for (const [key, item] of Object.entries(value)) (visit(key, item), walk(item, visit));
  };
  walk(rendered, (key, value) => {
    assert.notEqual(key === "continue-on-error" && value !== false, true, "continue-on-error is never enabled");
    if (key === "run") assert.equal(/(\|\|\s*(true|:)|;\s*exit\s+0)\s*$/m.test(String(value)), false, String(value));
  });
});

test("AC41: the router writes no SDLC_SYNC_STATE variable itself (the AC38 write scan passes)", () => {
  for (const text of [renderedText, readText(abs(ROUTER))]) {
    assert.equal(/gh variable|gh secret|actions\/variables/.test(text), false);
    assert.equal(/gh api[^\n]*(-X|--method)\s+(PATCH|POST|PUT|DELETE)/i.test(text), false);
  }
  const steps = jobOf(rendered).steps;
  for (const step of steps) assert.equal(/SDLC_SYNC_STATE/.test(String(step.run ?? "")), false, "the router script receives the edge as data");
});

