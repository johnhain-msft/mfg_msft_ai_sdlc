/**
 * `docs/SPEAKER-SCRIPT.md`: the read-aloud script, generated from the same model as the
 * speaker view and the script book.
 *
 * Shape, chosen for deck-density.py (`--script`):
 *   ### [SLIDE N] · <id> · <Title>   one heading per slide (the tool splits on it)
 *   plain paragraphs                 what you say (the only text the tool measures)
 *   > **[CUE]** KIND: ...            directions, asks, transitions: blockquotes are stripped
 *   > **Presenter:**, **The room sees:**, **Sources:**   per-slide header and footer: stripped
 *
 * There are no durations, no words-per-minute and no clock anywhere in it.
 */

import { presenterLabel, type Deck } from '../content/types';
import { roomSeesMarkdown } from '../shell/room';
import { renderBeatsMarkdown } from '../shell/script';

export function renderPresenterScript(deck: Deck): string {
  const { meta } = deck;
  const presenters = Object.values(meta.presenters)
    .map((p) => `${p.name} (${p.org})`)
    .join(', ');
  const out: string[] = [];
  out.push(`# Speaker Script: ${meta.title}`, '');
  out.push(`> Generated by \`node scripts/build.mjs\` from \`src/content/\`. Edit the content, not this file.`);
  out.push(`> ${meta.event} \u00b7 ${meta.session}`);
  out.push(`> Presenter: ${presenters}`, '');

  out.push('## How to read this script', '');
  out.push('- **Plain paragraphs are what you say.** Write them out loud, in your own rhythm.');
  out.push('- **Blockquotes are not read aloud.** `> **[CUE]**` lines are directions for you: SHOW, POINT, CLICK, WAIT, SWITCH and NOTE are actions; ASK, POLL and NEXT are lines you say to the room, kept in a quote so they stand out.');
  out.push('- **STORY SLOT** is a story only you can tell. The script never makes one up.');
  out.push('- **[IF NEEDED]** marks a deeper answer you reach for only when the question comes up.');
  out.push('- **Nothing here appears on the audience screen.** The deck shows sparse slides; press S in the deck for the speaker view, or R for the searchable script book.');
  out.push('- **Pacing is yours.** There is no clock in this script. Take the time the room needs.', '');

  for (const mod of deck.modules) {
    const inModule = deck.slides.map((s, i) => ({ s, n: i + 1 })).filter(({ s }) => s.moduleCode === mod.code);
    if (!inModule.length) continue;
    out.push(`## Module ${mod.code}: ${mod.title}`, '');
    for (const { s, n } of inModule) {
      out.push(`### [SLIDE ${n}] \u00b7 ${s.id} \u00b7 ${s.title}`, '');
      out.push(`> **Presenter:** ${presenterLabel(s.presenter)} \u00b7 **Module:** ${s.moduleCode}`);
      out.push(`> **Purpose:** ${s.purpose}`);
      out.push(...roomSeesMarkdown(s), '');
      out.push(...renderBeatsMarkdown(s));
      if (s.sources.length) {
        out.push(`> **Sources:** ${s.sources.map((x) => `[${x.label}](${x.url})`).join(' \u00b7 ')}`, '');
      }
    }
  }
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}
